static int td4160_panel_off(struct td4160_panel *ctx)
{
	struct mipi_dsi_multi_context dsi_ctx = { .dsi = ctx->dsi };

	mipi_dsi_dcs_write_seq_multi(&dsi_ctx, 0x28);
	mipi_dsi_msleep(&dsi_ctx, 50);
	mipi_dsi_dcs_write_seq_multi(&dsi_ctx, 0x10);
	mipi_dsi_msleep(&dsi_ctx, 120);

	return dsi_ctx.accum_err;
}

static int td4160_panel_prepare(struct drm_panel *panel)
{
	struct td4160_panel *ctx = to_td4160_panel(panel);
	struct device *dev = &ctx->dsi->dev;
	int ret;

	ret = reset_control_reset(ctx->reset);
	if (ret < 0) {
		dev_err(dev, "Failed to reset panel: %d\n", ret);
		return ret;
	}

	td4160_panel_reset(ctx);

	ret = td4160_panel_on(ctx);
	if (ret < 0) {
		dev_err(dev, "Failed to initialize panel: %d\n", ret);
		reset_control_assert(ctx->reset);
		return ret;
	}

	return 0;
}

static int td4160_panel_unprepare(struct drm_panel *panel)
{
	struct td4160_panel *ctx = to_td4160_panel(panel);
	struct device *dev = &ctx->dsi->dev;
	int ret;

	ret = td4160_panel_off(ctx);
	if (ret < 0)
		dev_err(dev, "Failed to un-initialize panel: %d\n", ret);

	reset_control_assert(ctx->reset);

	return 0;
}

